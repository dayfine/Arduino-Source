#!/usr/bin/env python3
"""Bazel equivalent of SerialPrograms/cmake/EmbedTextFiles.cmake."""
import pathlib
import sys


def main() -> None:
    out_path = pathlib.Path(sys.argv[1])
    header = sys.argv[2]
    ns = sys.argv[3]
    func = sys.argv[4]
    json_files = sorted(
        (pathlib.Path(p) for p in sys.argv[5:] if p.endswith(".json")),
        key=lambda p: p.name,
    )

    entries = []
    for path in json_files:
        text = path.read_text(encoding="utf-8")
        if not text or ')json"' in text:
            raise ValueError(f"{path} is empty or contains )json\"")
        parts = [
            f'            R"json({text[i : i + 16000]})json",'
            for i in range(0, len(text), 16000)
        ]
        entries.append(
            f'        {{"{path.stem}", join({{\n' + "\n".join(parts) + "\n        })},\n"
        )

    out_path.write_text(
        f"""// Generated by bazel_embed_text.py. Do not edit.
#include <initializer_list>
#include <string>
#include <utility>
#include <vector>
#include "{header}"

namespace {ns} {{
namespace {{
std::string join(std::initializer_list<const char*> parts) {{
    std::string text;
    for (const char* part : parts) {{
        text += part;
    }}
    return text;
}}
}}  // namespace

const std::vector<std::pair<std::string, std::string>>& {func}() {{
    static const std::vector<std::pair<std::string, std::string>> FILES{{
{"".join(entries)}    }};
    return FILES;
}}
}}  // namespace {ns}
""",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
